const GENERATED_PERMISSIONS: &str = "permissions/autogenerated";

fn main() {
    let attributes = if std::env::var_os("CARGO_FEATURE_BENCH").is_some() {
        tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(&["bench_stream"]))
    } else {
        let _ = std::fs::remove_dir_all(GENERATED_PERMISSIONS);
        tauri_build::Attributes::new()
    };
    tauri_build::try_build(attributes).expect("tauri-build가 실패했습니다");
}
