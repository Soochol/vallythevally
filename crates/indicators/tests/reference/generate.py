"""Writes the reference CSVs that crates/indicators/tests/reference.rs checks against.

Run from the repository root:
    uv run crates/indicators/tests/reference/generate.py
"""

import pathlib

import numpy as np
import talib

OUT = pathlib.Path(__file__).resolve().parent
BARS = 400
SEED = 20261109


def synthetic_bars():
    rng = np.random.default_rng(SEED)
    close = np.round(70_000 * np.exp(np.cumsum(rng.normal(0, 0.015, BARS))))
    open_ = np.round(np.concatenate([[70_000.0], close[:-1]]) * (1 + rng.normal(0, 0.004, BARS)))
    high = np.maximum(open_, close) + np.round(rng.uniform(50, 900, BARS))
    low = np.minimum(open_, close) - np.round(rng.uniform(50, 900, BARS))
    volume = np.round(rng.lognormal(13, 0.6, BARS))
    return open_, high, low, close, volume


def header(source, inputs):
    return [
        f"# source: {source}",
        f"# library: TA-Lib {talib.__version__} (C {talib.__ta_version__.decode()}), numpy {np.__version__}",
        f"# input: input.csv ({BARS} synthetic bars, numpy default_rng seed {SEED}); {inputs}",
        "# generated by: uv run crates/indicators/tests/reference/generate.py",
    ]


def write(name, comment, columns):
    lines = comment + [",".join(columns)]
    rows = zip(*columns.values())
    for row in rows:
        lines.append(",".join("" if np.isnan(v) else repr(float(v)) for v in row))
    (OUT / f"{name}.csv").write_text("\n".join(lines) + "\n")


def sma_of_valid(x, n):
    out = np.full_like(x, np.nan)
    valid = ~np.isnan(x)
    out[valid] = talib.SMA(x[valid], n)
    return out


def ema_of_valid(x, n):
    out = np.full_like(x, np.nan)
    valid = ~np.isnan(x)
    out[valid] = talib.EMA(x[valid], n)
    return out


def midpoint(high, low, n):
    out = np.full_like(high, np.nan)
    hh = np.lib.stride_tricks.sliding_window_view(high, n).max(axis=1)
    ll = np.lib.stride_tricks.sliding_window_view(low, n).min(axis=1)
    out[n - 1 :] = (hh + ll) / 2
    return out


def main():
    o, h, l, c, v = synthetic_bars()
    write("input", header("numpy random walk", "rounded to whole won like KRX prices"), {
        "open": o, "high": h, "low": l, "close": c, "volume": v,
    })

    for n in (5, 20):
        write(f"ma_sma_{n}", header(f"talib.SMA(close, {n})", f"spec ma sma {n}"), {"ma": talib.SMA(c, n)})
    write("ma_ema_12", header("talib.EMA(close, 12), seeded with the SMA of the first 12", "spec ma ema 12"),
          {"ma": talib.EMA(c, 12)})

    upper, middle, lower = talib.BBANDS(c, 20, 2.0, 2.0, 0)
    write("bollinger_20_2", header("talib.BBANDS(close, 20, 2, 2, SMA); population standard deviation", "spec bollinger 20 2"),
          {"upper": upper, "middle": middle, "lower": lower})

    conversion, base, span_b = midpoint(h, l, 9), midpoint(h, l, 26), midpoint(h, l, 52)
    write("ichimoku_9_26_52_26", header(
        "numpy sliding-window max/min, (highest high + lowest low) / 2; TA-Lib has no Ichimoku. "
        "Values are unshifted: spanA/spanB are drawn at +25 and lagging at -25 (backend.md 9.5)",
        "spec ichimoku 9 26 52 26"),
        {"conversion": conversion, "base": base, "spanA": (conversion + base) / 2, "spanB": span_b, "lagging": c})

    write("volume_20", header("talib.SMA(volume, 20)", "spec volume maPeriod 20"), {"volume": v, "ma": talib.SMA(v, 20)})

    rsi = talib.RSI(c, 14)
    write("rsi_14_9", header("talib.RSI(close, 14) (Wilder smoothing); signal = talib.SMA over the defined RSI values, 9",
                             "spec rsi 14 signal 9"), {"rsi": rsi, "signal": sma_of_valid(rsi, 9)})

    macd = talib.EMA(c, 12) - talib.EMA(c, 26)
    signal = ema_of_valid(macd, 9)
    write("macd_12_26_9", header(
        "talib.EMA(close, 12) - talib.EMA(close, 26), each seeded with its own SMA; signal = talib.EMA over the defined MACD "
        "values, 9. Not talib.MACD, which seeds the fast EMA late so that it starts on the slow EMA's first bar",
        "spec macd 12 26 9"), {"macd": macd, "signal": signal, "histogram": macd - signal})

    for k, d, smooth in ((5, 3, 3), (14, 5, 3)):
        slow_k, slow_d = talib.STOCH(h, l, c, fastk_period=k, slowk_period=smooth, slowk_matype=0,
                                     slowd_period=d, slowd_matype=0)
        write(f"stoch_slow_{k}_{d}_{smooth}", header(
            f"talib.STOCH(high, low, close, fastk={k}, slowk={smooth} SMA, slowd={d} SMA)",
            f"spec stochSlow k {k} d {d} smooth {smooth}"), {"k": slow_k, "d": slow_d})


main()
