import type { FinancialUpdatePage } from "../src/api/generated/FinancialUpdatePage";
import type { FinancialsPage } from "../src/api/generated/FinancialsPage";
import type { Layout } from "../src/api/generated/Layout";
import type { ChartSettings } from "../src/chart/settings";
import { financialListings } from "./financial-update-helpers";
import { cell, chartOf, DEFAULT_LAYOUT_ID, expect, test } from "./harness";

for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }, { width: 390, height: 844 }]) test.describe(`${viewport.width} 자동 재무자료 통합`, () => {
  const phone = viewport.width < 768;
  test.use({ viewport, isMobile: phone, hasTouch: phone, clockStart: "20170101070001", financialFixture: true, financialAutomatic: true, bootReplies: [financialListings] });
  test("자동 첫 수집·일일 정정·영속 정지·재개가 저장 지표와 가격을 유지한다", async ({ page, app }, info) => {
    test.setTimeout(120000);
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    const status = async (): Promise<FinancialUpdatePage> => (await fetch(`${app.url}/api/financial-update`)).json();
    const data = async (): Promise<FinancialsPage> => (await fetch(`${app.url}/api/symbols/005930/financials?period=Y`)).json();
    const layout: Layout = await (await fetch(`${app.url}/api/layouts/${DEFAULT_LAYOUT_ID}`)).json();
    const settings: ChartSettings = { v: 2, style: "candle", scale: "normal", compare: [], indicators: [{ id: "revenue", spec: { kind: "revenue" }, panel: "revenue", visible: true, style: { colors: ["ind-2"], width: 1 } }], panels: [{ id: "revenue", stretch: 0.4 }] };
    expect((await fetch(`${app.url}/api/layouts/${layout.id}`, { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify({ ...layout, revision: layout.revision + 1, cells: [{ ...layout.cells[0], symbol: "005930", venue: "combined", period: "Y", chartSettings: settings }] }) })).ok).toBe(true);
    await expect.poll(async () => (await status()).historyComplete, { timeout: 45000 }).toBe(true);
    const initial = await status();
    expect(initial.automatic).toBe(true);
    expect(initial.nextCheckAt).toBe(Date.parse("2017-01-02T07:00:00+09:00") / 1000);
    expect((await data()).series.find((series) => series.metric === "revenue")!.points.find((point) => point.businessYear === 2015)!.value).toBe(1000);
    await page.goto("/");
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    const dialog = page.getByRole("dialog", { name: "재무자료", exact: true });
    await expect(dialog).toContainText("전체 이력 확인 완료");
    await expect(dialog).toContainText("다음 자동 확인");
    await expect(dialog).toContainText("2017. 1. 2. 오전 7:00:00");
    await page.screenshot({ path: info.outputPath("automatic-first-ready.png") });
    const firstCalls = app.dart!.calls.length;
    await app.restart({ clockStart: "20170102065000" });
    expect((await status()).id).toBe(initial.id);
    expect(app.dart!.calls).toHaveLength(firstCalls);
    let release: () => void = () => {};
    const scope = "fnlttSinglAcntAll.json/2015/11013/00126380";
    app.dart!.corrected = true;
    app.dart!.block = { scope, wait: new Promise<void>((resolve) => { release = resolve; }) };
    await app.restart({ clockStart: "20170102070001" });
    await expect.poll(() => app.dart!.calls.filter((call) => call === scope).length, { timeout: 45000 }).toBe(2);
    await page.reload();
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    expect(Number(await chartOf(cell(page)).getAttribute("data-bar-count"))).toBeGreaterThan(0);
    expect((await data()).series.find((series) => series.metric === "revenue")!.points.find((point) => point.businessYear === 2015)!.value).toBe(1000);
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    await dialog.getByRole("button", { name: "일시정지", exact: true }).click();
    await expect(dialog).toContainText("일시정지 처리 중");
    release(); app.dart!.block = null;
    await expect(dialog).toContainText("일시정지됨");
    const paused = await status();
    expect(paused.nextCheckAt).toBeNull();
    const pausedCalls = app.dart!.calls.length;
    await page.screenshot({ path: info.outputPath("automatic-user-paused.png") });
    await app.restart({ clockStart: "20170103070001" });
    await page.reload();
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    await expect(dialog).toContainText("일시정지됨");
    expect(app.dart!.calls).toHaveLength(pausedCalls);
    await dialog.getByRole("button", { name: "재개", exact: true }).click();
    await expect(dialog).toContainText("전체 이력 확인 완료", { timeout: 45000 });
    const done = await status();
    expect(done.id).toBe(paused.id);
    expect(done.lastCheckedAt).toBeGreaterThan(initial.lastCheckedAt!);
    expect(done.nextCheckAt).toBe(Date.parse("2017-01-04T07:00:00+09:00") / 1000);
    expect(app.dart!.calls.filter((call) => call === scope)).toHaveLength(2);
    expect((await data()).series.find((series) => series.metric === "revenue")!.points.find((point) => point.businessYear === 2015)!.value).toBe(1200);
    await page.screenshot({ path: info.outputPath("automatic-correction-ready.png") });
    const doneCalls = app.dart!.calls.length;
    await app.restart({ clockStart: "20170103080000" });
    expect((await status()).id).toBe(done.id);
    expect(app.dart!.calls).toHaveLength(doneCalls);
    await dialog.getByRole("button", { name: "닫기", exact: true }).first().click();
    await expect(page.locator('[data-indicator-row="revenue"]')).toContainText("확인 완료");
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBe(0);
    expect(errors).toEqual([]);
  });
});
