import type { FinancialUpdatePage } from "../src/api/generated/FinancialUpdatePage";
import { financialListings } from "./financial-update-helpers";
import { cell, chartOf, expect, test } from "./harness";

for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }, { width: 390, height: 844 }]) test.describe(`${viewport.width} 인증·한도 정지`, () => {
  const phone = viewport.width < 768;
  test.use({ viewport, isMobile: phone, hasTouch: phone, clockStart: "20151231060000", financialFixture: true, bootReplies: [financialListings] });
  for (const failure of [{ code: "010", reason: "authentication", scope: "fnlttXbrl.xml", text: "인증 오류" }, { code: "020", reason: "rate_limited", scope: "corpCode.xml", text: "호출 한도" }]) test(`${failure.reason} 정지를 보존하고 확인 요청 하나 뒤 재개한다`, async ({ page, app }, info) => {
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    app.dart!.fail = failure.scope;
    app.dart!.failStatus = failure.code;
    await page.goto("/?symbol=005930");
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    const dialog = page.getByRole("dialog", { name: "재무자료", exact: true });
    await dialog.getByRole("button", { name: "전체 업데이트", exact: true }).click();
    const status = async (): Promise<FinancialUpdatePage> => (await fetch(`${app.url}/api/financial-update`)).json();
    await expect.poll(async () => (await status()).status).toBe("stopped");
    await expect(dialog).toContainText(failure.text);
    if (failure.reason === "rate_limited") {
      await expect(dialog).toContainText("다음 확인 기준");
      await expect(dialog).toContainText("2015. 12. 31. 오전 7:00:00");
    } else await expect(dialog).toContainText("인증 설정을 수정한 뒤");
    await expect(dialog.getByRole("button", { name: "확인 후 재개", exact: true })).toBeEnabled();
    const initial = await status();
    expect(initial.stopReason).toBe(failure.reason);
    const calls = app.dart!.calls.length;
    await page.screenshot({ path: info.outputPath(`${failure.reason}-stopped.png`) });
    await app.restart({ clockStart: "20160101070000" });
    await page.reload();
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    await expect(dialog).toContainText(failure.text);
    expect(app.dart!.calls).toHaveLength(calls);
    let release: () => void = () => {};
    app.dart!.block = { scope: failure.scope, wait: new Promise<void>((resolve) => { release = resolve; }) };
    await dialog.getByRole("button", { name: "확인 후 재개", exact: true }).click();
    await expect(dialog).toContainText("재개 확인 중");
    await expect(dialog.getByRole("button", { name: "확인 중", exact: true })).toBeDisabled();
    for (let i = 0; i < 3; i++) await fetch(`${app.url}/api/financial-update/resume`, { method: "POST" });
    expect(app.dart!.calls).toHaveLength(calls + 1);
    await page.screenshot({ path: info.outputPath(`${failure.reason}-checking.png`) });
    release(); app.dart!.block = null;
    await expect.poll(async () => (await status()).status).toBe("stopped");
    await expect(dialog.getByRole("button", { name: "확인 후 재개", exact: true })).toBeEnabled();
    expect(app.dart!.calls).toHaveLength(calls + 1);
    if (failure.reason === "rate_limited") expect((await status()).nextCheckAt).toBe(Date.parse("2016-01-02T07:00:00+09:00") / 1000);
    app.dart!.fail = null;
    await dialog.getByRole("button", { name: "확인 후 재개", exact: true }).click();
    await expect(dialog).toContainText("전체 이력 확인 완료", { timeout: 45000 });
    expect((await status()).id).toBe(initial.id);
    expect(await dialog.innerText()).not.toContain("SYNTHETIC-DART-E2E");
    await page.screenshot({ path: info.outputPath(`${failure.reason}-resumed.png`) });
    await dialog.getByRole("button", { name: "닫기", exact: true }).first().click();
    expect(Number(await chartOf(cell(page)).getAttribute("data-bar-count"))).toBeGreaterThan(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBe(0);
    expect(errors).toEqual([]);
  });
});
