import type { FinancialUpdatePage } from "../src/api/generated/FinancialUpdatePage";
import type { Layout } from "../src/api/generated/Layout";
import type { ChartSettings } from "../src/chart/settings";
import { financialListings } from "./financial-update-helpers";
import { cell, chartOf, DEFAULT_LAYOUT_ID, expect, test } from "./harness";

for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }, { width: 390, height: 844 }]) test.describe(`${viewport.width} 과거 이력·일시정지`, () => {
  const phone = viewport.width < 768;
  test.use({ viewport, isMobile: phone, hasTouch: phone, clockStart: "20200101120000", financialFixture: true, bootReplies: [financialListings] });
  test("최근 완료 뒤 과거 단계에서 멈추고 재시작·재개해 전체 이력을 완료한다", async ({ page, app }, info) => {
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    const layout: Layout = await (await fetch(`${app.url}/api/layouts/${DEFAULT_LAYOUT_ID}`)).json();
    const settings: ChartSettings = { v: 2, style: "candle", scale: "normal", compare: [], indicators: [{ id: "revenue", spec: { kind: "revenue" }, panel: "revenue", visible: true, style: { colors: ["ind-2"], width: 1 } }], panels: [{ id: "revenue", stretch: 0.4 }] };
    expect((await fetch(`${app.url}/api/layouts/${layout.id}`, { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify({ ...layout, revision: layout.revision + 1, cells: [{ ...layout.cells[0], symbol: "005930", venue: "combined", period: "Y", chartSettings: settings }] }) })).ok).toBe(true);
    let release: () => void = () => {};
    const scope = "fnlttSinglAcntAll.json/2016/11013/00126380";
    app.dart!.block = { scope, wait: new Promise<void>((resolve) => { release = resolve; }) };
    await page.goto("/");
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    const dialog = page.getByRole("dialog", { name: "재무자료", exact: true });
    await dialog.getByRole("button", { name: "전체 업데이트", exact: true }).click();
    await expect(dialog).toContainText("최근 자료 수집 중");
    await expect.poll(() => app.dart!.calls.includes(scope), { timeout: 45000 }).toBe(true);
    await expect(dialog).toContainText("과거 이력 수집 중");
    const status = async (): Promise<FinancialUpdatePage> => (await fetch(`${app.url}/api/financial-update`)).json();
    const history = await status();
    expect(history.completedCompanies).toBe(2);
    expect(history.historyCompletedCompanies).toBe(1);
    expect(history.historyComplete).toBe(false);
    await dialog.getByRole("button", { name: "일시정지", exact: true }).click();
    await expect(dialog).toContainText("일시정지 처리 중");
    await expect(dialog).toContainText("사용자 요청");
    await page.screenshot({ path: info.outputPath("history-pausing.png") });
    release(); app.dart!.block = null;
    await expect(dialog).toContainText("일시정지됨");
    const paused = await status();
    expect(paused.phase).toBe("history");
    expect(paused.historyComplete).toBe(false);
    const calls = app.dart!.calls.length;
    await page.screenshot({ path: info.outputPath("history-paused.png") });
    await app.restart({ clockStart: "20210101120000" });
    await page.reload();
    await expect(cell(page)).toHaveAttribute("aria-busy", "false");
    await page.getByRole("button", { name: "재무자료", exact: true }).filter({ visible: true }).click();
    await expect(dialog).toContainText("일시정지됨");
    await expect(dialog).toContainText("사용자 요청");
    expect(app.dart!.calls).toHaveLength(calls);
    expect((await status()).completedCompanies).toBe(2);
    const recent = app.dart!.calls.filter((call) => /\/(2017|2018|2019|2020)\//.test(call));
    await dialog.getByRole("button", { name: "재개", exact: true }).click();
    await expect(dialog).toContainText("전체 이력 확인 완료", { timeout: 45000 });
    const done = await status();
    expect(done.id).toBe(history.id);
    expect(done.phase).toBe("complete");
    expect(done.throughYear).toBe(2020);
    expect(done.historyCompletedCompanies).toBe(2);
    expect(done.historyComplete).toBe(true);
    expect(app.dart!.calls.filter((call) => /\/(2017|2018|2019|2020)\//.test(call))).toEqual(recent);
    expect(app.dart!.calls.filter((call) => call === scope)).toHaveLength(1);
    await page.screenshot({ path: info.outputPath("history-complete.png") });
    await dialog.getByRole("button", { name: "닫기", exact: true }).first().click();
    await expect(page.locator('[data-indicator-row="revenue"]')).toContainText("확인 완료");
    expect(Number(await chartOf(cell(page)).getAttribute("data-bar-count"))).toBeGreaterThan(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBe(0);
    expect(errors).toEqual([]);
  });
});
